def main() -> int:
    root = Path(__file__).resolve().parents[2]
    try:
        import torch
        runtime = f"torch {torch.__version__}"
    except ImportError:
        runtime = "torch not installed in this env"
    lines = ["# Release Manifest - Submission Baseline SB-1 (UTF-8)",
             "", "Generated by `scripts/release/build_manifest.py` (hashes recomputed).",
             f"Runtime here: {runtime}; python {sys.version.split()[0]}.", ""]
    missing = []
    for section, paths in FILES.items():
        lines.append(f"## {section}")
        for p in paths:
            fp = root / p
            if fp.is_file():
                lines.append(f"- `{p}` `{sha(fp)}` ({fp.stat().st_size} bytes)")
            else:
                lines.append(f"- `{p}` MISSING")
                missing.append(p)
        lines.append("")
    lines += ["## Status",
              "- SB-1 submission-ready fallback: CLS-001 + SEG-001 + UNC-001 "
              "(descriptive) + ROB-001 (documented variant) + FP16/autocast.",
              "- CPU CI: 49 passed (48 unit+integration + 1 data-gate; synthetic images only).",
              "- Locked evaluations closed; no tuning/re-cut permitted.",
              "- NOT included: optimizer-state `last.pt` files (remain on kernels), "
              "Kaggle HTML logs, tmp snapshots, `__pycache__`.",
              "- Claim boundary: measured BRISC-regime engineering results; "
              "not clinical diagnostic accuracy.", ""]
    (root / "docs" / "release_manifest.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"manifest written; missing={missing if missing else 'none'}")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
